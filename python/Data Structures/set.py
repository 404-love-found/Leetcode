'''
集合是一个不包含重复元素的无序容器，底层也是用哈希表实现的。
它最大的特点是 in 判断非常快（O(1)），比列表的 in（O(n)）快得多
当你需要频繁判断"某个元素是否存在"的时候，一定要用集合
'''


# 从列表创建集合（自动去重）
nums = [1, 2, 2, 3, 3, 3]
s2 = set(nums)
print("去重后的集合：",s2)



# add：添加元素
nums = [1, 2, 3]
s = set(nums)
s.add(6)
s.add(3)  # 已存在，不会重复添加
print("新集合：",s)

s.remove(2)  # 删除元素，如果不存在会报 KeyError
# discard：删除元素（不存在也不会报错）
s.discard(99)  # 不存在，不报错
print("删除元素后：",s)

# in 判断（O(1)，非常快）
print("4在集合中：", 4 in s)
print("99在集合中：", 99 in s)

